function enFromKo(key, koText) {
  let s = koText;
  for (const [from, to] of EN_WORD) s = s.split(from).join(to);
  if (/[\u3131-\uD7A3]/.test(s)) {
    return key
      .replace(/^admin_ops_tools_/, "")
      .replace(/_/g, " ")
      .replace(/\b\w/g, (c) => c.toUpperCase());
  }
  return s;
}

