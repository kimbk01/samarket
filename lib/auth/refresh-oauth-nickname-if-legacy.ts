import { isAutoGeneratedDibayId } from "@/lib/auth/dibay-id-policy";
import type { OAuthProfileSeed } from "@/lib/auth/oauth-profile-seed";
import { DEFAULT_OAUTH_DISPLAY_NAME } from "@/lib/auth/post-login-profile-policy";

export type OAuthNicknameProfileInput = {
  onboarding_completed_at?: string | null;
  nickname?: string | null;
  display_name?: string | null;
};

function pickTrimmed(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : null;
}

function isLegacyAutoNickname(value: string | null | undefined): boolean {
  return isAutoGeneratedDibayId(value);
}

/**
 * 시스템 임시 닉네임 「DIBAY 사용자」 — SNS 가 이름을 주지 않아 넣은 값 (회원이 고른 닉네임이 아님).
 * Apple 은 이름을 첫 로그인 때 한 번만 주므로, 이름이 들어오면 가입 완료 여부와 관계없이 교체한다
 * (Owner 「수정 진행」 2026-11-08). 회원이 직접 바꾼 닉네임은 이 값이 아니므로 덮어쓰지 않는다.
 */
function isSystemPlaceholderNickname(value: string | null | undefined): boolean {
  return pickTrimmed(value) === DEFAULT_OAUTH_DISPLAY_NAME;
}

export function shouldRefreshNicknameFromOAuth(
  profile: OAuthNicknameProfileInput | null | undefined,
  nicknameCandidate: string | null | undefined
): boolean {
  const candidate = pickTrimmed(nicknameCandidate);
  if (!candidate || candidate === DEFAULT_OAUTH_DISPLAY_NAME) return false;

  const nickname = pickTrimmed(profile?.nickname);
  const displayName = pickTrimmed(profile?.display_name);

  if (isSystemPlaceholderNickname(nickname) && (!displayName || isSystemPlaceholderNickname(displayName))) {
    return true;
  }
  if (profile?.onboarding_completed_at) return false;

  if (!nickname && !displayName) return true;
  if (isLegacyAutoNickname(nickname) || isLegacyAutoNickname(displayName)) return true;
  return false;
}

export function buildOAuthNicknamePatch(
  profile: OAuthNicknameProfileInput | null | undefined,
  seed: Pick<OAuthProfileSeed, "nicknameCandidate">
): { nickname?: string; display_name?: string } | null {
  if (!shouldRefreshNicknameFromOAuth(profile, seed.nicknameCandidate)) return null;
  const candidate = pickTrimmed(seed.nicknameCandidate);
  if (!candidate) return null;
  return { nickname: candidate, display_name: candidate };
}
