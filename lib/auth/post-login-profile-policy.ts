import { isAutoGeneratedDibayId } from "@/lib/auth/dibay-id-policy";
import { isDibayIdComplete, type DibaySignupProfileInput } from "@/lib/auth/dibay-signup-status";
import { verifiedPhoneVerdict, type StoredPhoneFact } from "@/lib/auth/store-member-policy";

export function pickTrimmedProfileField(input: unknown): string | null {
  if (typeof input !== "string") return null;
  const trimmed = input.trim();
  return trimmed.length > 0 ? trimmed : null;
}


const DISPLAY_NAME_MIN = 2;
const DISPLAY_NAME_MAX = 20;

/** 표시 이름 유효 — auto dibay_* 제외, 2~20자 */
export function hasValidDisplayName(profile: {
  display_name?: string | null;
  nickname?: string | null;
} | null | undefined): boolean {
  if (!profile) return false;
  const name =
    pickTrimmedProfileField(profile.display_name) ?? pickTrimmedProfileField(profile.nickname);
  if (!name) return false;
  if (isAutoGeneratedDibayId(name)) return false;
  return name.length >= DISPLAY_NAME_MIN && name.length <= DISPLAY_NAME_MAX;
}

export type PhoneVerificationGateInput = {
  phone_verified?: boolean | null;
  phone_verified_at?: string | null;
  phone_verification_method?: string | null;
  role?: string | null;
  /** Server-resolved membership-only Admin fact (client snapshot) */
  privilegedAdmin?: boolean;
  /** Legacy dual-write mirror — not Application/Client Admin allow */
  is_admin?: boolean | null;
  provider?: string | null;
  auth_provider?: string | null;
  email?: string | null;
} & StoredPhoneFact;

/** SSOT — 클라·서버 profile gate 동일 판정. 구현은 `verifiedPhoneVerdict` 하나(표시 `deriveStoreMemberStatus` 와 공유). */
export function hasVerifiedPhone(profile: PhoneVerificationGateInput | null | undefined): boolean {
  if (!profile) return false;
  // Canonical only — never promote profiles.is_admin mirror to Admin exemption
  const privilegedAdmin =
    typeof profile.privilegedAdmin === "boolean" ? profile.privilegedAdmin : undefined;
  return verifiedPhoneVerdict({ ...profile, privilegedAdmin });
}

