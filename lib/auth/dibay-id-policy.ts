/** DIBAY public @id — DB stores without leading @ */

export const DIBAY_ID_RE = /^[a-z0-9](?:[a-z0-9_.]{2,18}[a-z0-9])$/;

export const DIBAY_ID_RESERVED = new Set([
  "admin",
  "administrator",
  "support",
  "owner",
  "system",
  "official",
  "staff",
  "root",
  "mod",
  "help",
  "dibay",
  "samarket",
]);

/**
 * 서버 자동 발급 @id 형식 (설계안 ⑦, Owner 2026-11-08)
 * - 신규: `dibay` + 숫자 6~7자리 (예: dibay482913)
 * - 기존: `dibay_` + 16진수 6자리 (2026-07 ~ 2026-11 발급분, 그대로 유지)
 */
const DIBAY_AUTO_PATTERNS: readonly RegExp[] = [/^dibay[0-9]{6,7}$/, /^dibay_[a-f0-9]{6}$/];

/** `dibay` 로 시작하는 @id 는 시스템 전용 — 사용자·관리자 지정 불가 (기존 보유자는 유지) */
export const DIBAY_ID_SYSTEM_PREFIX = "dibay";

/**
 * 중복 판정 키 — 소문자 + `.`·`_` 제거. `kim_bk`·`kimbk`·`kim.bk` 는 같은 아이디로 본다 (설계안 ⑧).
 * DB `profiles.dibay_id_key`(생성 컬럼·유일 인덱스)와 같은 규칙.
 */
export function dibayIdSimilarityKey(value: string | null | undefined): string {
  return String(value ?? "")
    .trim()
    .toLowerCase()
    .replace(/^@+/, "")
    .replace(/[._]/g, "");
}

export function normalizeDibayIdInput(v: unknown): string {
  return String(v ?? "")
    .trim()
    .toLowerCase()
    .replace(/^@+/, "");
}

export function isAutoGeneratedDibayId(value: string | null | undefined): boolean {
  const trimmed = typeof value === "string" ? value.trim().toLowerCase() : "";
  return Boolean(trimmed && DIBAY_AUTO_PATTERNS.some((re) => re.test(trimmed)));
}

export function isValidDibayIdFormat(normalized: string): boolean {
  if (!normalized || !DIBAY_ID_RE.test(normalized)) return false;
  if (DIBAY_ID_RESERVED.has(normalized)) return false;
  if (isAutoGeneratedDibayId(normalized)) return false;
  if (isSystemReservedDibayIdPrefix(normalized)) return false;
  return true;
}

/** `dibay`·`dibay.`·`dibay_` 로 시작 — 시스템 전용 (자동 발급 사칭 방지) */
export function isSystemReservedDibayIdPrefix(normalized: string): boolean {
  return dibayIdSimilarityKey(normalized).startsWith(DIBAY_ID_SYSTEM_PREFIX);
}

/** 아이디 변경 실패 사유 → 한국어 안내 (관리자·회원 화면 공통) */
export function dibayIdErrorMessageKo(code: string | null | undefined): string | null {
  switch (String(code ?? "")) {
    case "dibay_id_taken":
      return "이미 사용 중인 아이디입니다.";
    case "dibay_id_similar_taken":
      return "비슷한 아이디(점·밑줄만 다름)가 이미 있습니다. 다른 아이디를 입력하세요.";
    case "dibay_id_reserved_prefix":
      return "dibay 로 시작하는 아이디는 시스템 전용이라 사용할 수 없습니다.";
    default:
      return null;
  }
}
