/**
 * DIBAY @public-id SSOT — 카톡·텔레그램식 단일 정의
 *
 * CONTRACT
 * - UI·gate·검색·메신저 subtitle 은 이 파일만 해석한다.
 * - `dibay_id` / audit fields / `username_confirmed` / `dibay_id_locked` 를 화면마다 따로 조합하지 않는다.
 *
 * DO NOT
 * - `dibay_id_locked === true ? true : null` 같은 username_confirmed 추측을 다른 파일에 두지 않는다.
 * - auto-assigned `dibay_*` 를 부분일치(prefix·contains·닉네임) 검색에 노출하지 않는다 (gate 는 통과).
 *   친구 찾기·아이디 조회 판정은 DB `cm_search_members` 한 곳 (회원 아이디 v3 §3.3).
 */

import { DIBAY_AUTO_ID_V3_RE, isAutoGeneratedDibayId, normalizeDibayIdInput } from "@/lib/auth/dibay-id-policy";
import { formatAtUsername } from "@/lib/users/user-label";

/** profiles @public-id 관련 최소 필드 — fetch·gate·UI 공통 */
/** DB `profiles.dibay_id_state` (생성 컬럼) — 회원 아이디 상태 단일 판정 (설계안 v3 §3.1) */
export type PublicIdState = "none" | "auto" | "auto_legacy" | "custom";

export type ProfilePublicIdFields = {
  dibay_id?: string | null;
  /** DB 생성 컬럼 — 있으면 이 값만 쓴다 */
  dibay_id_state?: PublicIdState | string | null;
  /** DB 생성 컬럼 — 회원 본인 1회 변경 가능 */
  dibay_id_can_change?: boolean | null;
  dibay_id_locked?: boolean | null;
  dibay_id_auto_assigned?: boolean | null;
  dibay_id_initial?: string | null;
  dibay_id_changed_once?: boolean | null;
  dibay_id_changed_at?: string | null;
  username?: string | null;
  username_confirmed?: boolean | null;
};

const PUBLIC_ID_STATES: readonly PublicIdState[] = ["none", "auto", "auto_legacy", "custom"];

/**
 * 회원 아이디 상태 — DB `dibay_id_state` 를 쓴다.
 * 그 칸을 조회하지 않은 행만 DB 생성 컬럼과 같은 식으로 계산한다
 * (supabase/migrations/20271111160000_member_id_v3_state_search_qr.sql §2 — 식을 바꾸면 둘 다 바꾼다).
 */
export function resolvePublicIdState(row: ProfilePublicIdFields | null | undefined): PublicIdState {
  if (!row) return "none";
  const db = typeof row.dibay_id_state === "string" ? row.dibay_id_state : null;
  if (db && (PUBLIC_ID_STATES as readonly string[]).includes(db)) return db as PublicIdState;
  const id = (pickTrimmed(row.dibay_id) ?? "").toLowerCase();
  if (!id) return "none";
  const initial = (pickTrimmed(row.dibay_id_initial) ?? "").toLowerCase();
  const untouched = row.dibay_id_auto_assigned === true && row.dibay_id_changed_once !== true && id === initial;
  if (!untouched) return "custom";
  return DIBAY_AUTO_ID_V3_RE.test(id) ? "auto" : "auto_legacy";
}

/** 회원 본인 1회 변경 가능 — DB `dibay_id_can_change` (없으면 같은 식으로 계산) */
export function resolvePublicIdCanChange(row: ProfilePublicIdFields | null | undefined): boolean {
  if (!row) return false;
  if (typeof row.dibay_id_can_change === "boolean") return row.dibay_id_can_change;
  if (!pickTrimmed(row.dibay_id)) return false;
  if (row.dibay_id_changed_once === true) return false;
  return row.dibay_id_auto_assigned === true || row.dibay_id_locked !== true;
}

export type PublicIdProfileView = {
  /** 기능 gate(친구추가·내정보 CTA·프로필 완성) */
  setupComplete: boolean;
  /** @handle UI — auto-assigned 포함 */
  atDisplay: string | null;
  /** 프로필 수정 입력 seed(확정 전 draft 포함) */
  inputSeed: string;
  /** 검색·메신저 subtitle·publicId 노출용(커스텀 확정만) */
  searchableId: string | null;
  locked: boolean;
  autoAssigned: boolean;
  canChangeOnce: boolean;
  changeComplete: boolean;
};

function pickTrimmed(input: unknown): string | null {
  if (typeof input !== "string") return null;
  const trimmed = input.trim();
  return trimmed.length > 0 ? trimmed : null;
}

function resolveDibayIdRaw(row: ProfilePublicIdFields | null | undefined): string | null {
  if (!row) return null;
  const dibay = pickTrimmed(row.dibay_id);
  if (dibay) return normalizeDibayIdInput(dibay);
  return null;
}

/** DB row → gate 입력. username_confirmed 누락 시 locked 로만 보수 추론. */
export function normalizeProfilePublicIdFields(
  row: ProfilePublicIdFields
): Required<Pick<ProfilePublicIdFields, "dibay_id" | "dibay_id_locked" | "username" | "username_confirmed">> {
  return {
    dibay_id: row.dibay_id ?? null,
    dibay_id_locked: row.dibay_id_locked ?? null,
    username: row.username ?? null,
    username_confirmed:
      row.username_confirmed === true || row.username_confirmed === false
        ? row.username_confirmed
        : row.dibay_id_locked === true
          ? true
          : null,
  };
}

/** dibay_id 우선, 없으면 username — @ 제거·소문자. auto dibay_* 는 null. */
export function resolveCanonicalPublicIdRaw(row: ProfilePublicIdFields | null | undefined): string | null {
  if (!row) return null;
  const raw = normalizeDibayIdInput(pickTrimmed(row.dibay_id) ?? pickTrimmed(row.username) ?? "");
  if (!raw || isAutoGeneratedDibayId(raw)) return null;
  return raw;
}

/** 친구검색·메신저 subtitle·publicId — 커스텀 확정 id 만 */
export function resolveSearchablePublicId(row: ProfilePublicIdFields | null | undefined): string | null {
  if (!row) return null;
  const normalized = normalizeProfilePublicIdFields(row);
  const dibay = pickTrimmed(normalized.dibay_id);
  if (dibay) {
    const id = normalizeDibayIdInput(dibay);
    if (id && !isAutoGeneratedDibayId(id)) return id;
    return null;
  }
  if (normalized.username_confirmed === true) {
    const username = normalizeDibayIdInput(pickTrimmed(normalized.username) ?? "");
    return username && !isAutoGeneratedDibayId(username) ? username : null;
  }
  return null;
}

/** @handle UI — auto-assigned 포함, 미부여 시 null */
export function resolvePublicIdAtDisplay(row: ProfilePublicIdFields | null | undefined): string | null {
  const dibayRaw = resolveDibayIdRaw(row);
  if (dibayRaw) return formatAtUsername(dibayRaw);
  const searchable = resolveSearchablePublicId(row);
  return searchable ? formatAtUsername(searchable) : null;
}

/** 프로필 수정·온보딩 입력 seed */
export function resolvePublicIdInputSeed(row: ProfilePublicIdFields | null | undefined): string {
  return resolveCanonicalPublicIdRaw(row) ?? "";
}

/** 서버 자동 발급 아이디를 바꾸지 않은 회원 (DB 상태 auto · auto_legacy) — gate 통과 */
export function isAutoAssignedPublicIdHeld(row: ProfilePublicIdFields | null | undefined): boolean {
  if (!row) return false;
  if (typeof row.dibay_id_state === "string") {
    const st = resolvePublicIdState(row);
    return st === "auto" || st === "auto_legacy";
  }
  if (row.dibay_id_auto_assigned !== true) return false;
  const dibayRaw = resolveDibayIdRaw(row);
  return Boolean(dibayRaw && isAutoGeneratedDibayId(dibayRaw) && row.dibay_id_changed_once !== true);
}

/** 기능 gate 단일 진입점 */
export function isPublicIdSetupComplete(row: ProfilePublicIdFields | null | undefined): boolean {
  if (!row) return false;
  if (isAutoAssignedPublicIdHeld(row)) return true;

  const normalized = normalizeProfilePublicIdFields(row);
  const canonical = resolveCanonicalPublicIdRaw(normalized);
  if (!canonical) return false;
  if (normalized.username_confirmed === false) return false;
  if (normalized.dibay_id_locked === true) return true;
  if (normalized.username_confirmed === true && pickTrimmed(normalized.username)) return true;
  return false;
}

/** 내정보·프로필수정 — 한 번에 */
export function evaluatePublicIdProfileView(row: ProfilePublicIdFields | null | undefined): PublicIdProfileView {
  const normalized = normalizeProfilePublicIdFields(row ?? {});
  const setupComplete = isPublicIdSetupComplete(row);
  const dibayRaw = resolveDibayIdRaw(row);
  const autoAssigned = isAutoAssignedPublicIdHeld(row);
  const changeComplete =
    row?.dibay_id_changed_once === true &&
    Boolean(dibayRaw && !isAutoGeneratedDibayId(dibayRaw));
  /**
   * 회원 본인 변경권 — DB `dibay_id_can_change` (confirm_dibay_id 허용 조건과 같은 식, 설계안 v3 D13).
   * 관리자가 바꾼 회원(변경권 미사용)·관리자가 변경권을 다시 준 회원도 여기서 true.
   */
  const canChangeOnce = resolvePublicIdCanChange(row);
  const atDisplay = dibayRaw ? formatAtUsername(dibayRaw) : resolvePublicIdAtDisplay(normalized);

  return {
    setupComplete,
    atDisplay: setupComplete || autoAssigned || changeComplete ? atDisplay : null,
    inputSeed: resolvePublicIdInputSeed(normalized),
    searchableId: resolveSearchablePublicId(normalized),
    locked: normalized.dibay_id_locked === true && !canChangeOnce,
    autoAssigned,
    canChangeOnce,
    changeComplete,
  };
}

/** @deprecated — normalizeProfilePublicIdFields 사용 */
export const profileFieldsForDibayIdComplete = normalizeProfilePublicIdFields;

/** @deprecated — isPublicIdSetupComplete 사용 */
export function isDibayIdComplete(row: ProfilePublicIdFields | null | undefined): boolean {
  return isPublicIdSetupComplete(row);
}
