import { describe, expect, it } from "vitest";
import { resolveMemberPublicIdUi } from "@/lib/auth/member-public-id-ui-contract";
import { isAutoGeneratedDibayId, isValidDibayIdFormat } from "@/lib/auth/dibay-id-policy";
import { resolvePublicIdCanChange, resolvePublicIdState } from "@/lib/auth/dibay-public-id-ssot";
import { isDefaultDibayPublicId } from "@/lib/profile/profile-completed";

/** 설계안 v3 §3.1·§3.8 — 회원 화면 아이디 1개 · 배지·안내·CTA 단일 계약 */
describe("member public id UI contract", () => {
  it("auto (5 digits + word, unchanged): one id, can-change badge, 5-digit hint, change CTA", () => {
    const ui = resolveMemberPublicIdUi({ dibay_id: "48213sun", dibay_id_state: "auto", dibay_id_can_change: true });
    expect(ui).toMatchObject({
      state: "auto",
      atDisplay: "@48213sun",
      badgeKey: "member_id_badge_can_change",
      hintKey: "member_id_hint_auto",
      hintVars: { digits: "48213" },
      changeCtaKey: "member_id_cta_change",
      changeConfirmNoteVars: { current: "48213sun" },
    });
  });

  it("legacy auto id: full-id hint", () => {
    const ui = resolveMemberPublicIdUi({ dibay_id: "dibay482913", dibay_id_state: "auto_legacy", dibay_id_can_change: true });
    expect(ui.hintKey).toBe("member_id_hint_legacy");
    expect(ui.hintVars.digits).toBe("");
  });

  it("changed id: no badge, no CTA, 4+ letters hint, never shows the base id", () => {
    const ui = resolveMemberPublicIdUi({
      dibay_id: "minji.kim",
      dibay_id_initial: "48213sun",
      dibay_id_state: "custom",
      dibay_id_can_change: false,
    });
    expect(ui).toMatchObject({ atDisplay: "@minji.kim", badgeKey: null, changeCtaKey: null, hintKey: "member_id_hint_custom" });
    expect(JSON.stringify(ui)).not.toContain("48213sun");
  });

  it("DB values win; without them the same formula as the DB generated columns is used", () => {
    expect(resolvePublicIdState({ dibay_id: "48213sun", dibay_id_state: "custom" })).toBe("custom");
    expect(
      resolvePublicIdState({
        dibay_id: "48213sun",
        dibay_id_initial: "48213sun",
        dibay_id_auto_assigned: true,
        dibay_id_changed_once: false,
      }),
    ).toBe("auto");
    expect(
      resolvePublicIdState({
        dibay_id: "dibay_0d9d04",
        dibay_id_initial: "dibay_0d9d04",
        dibay_id_auto_assigned: true,
      }),
    ).toBe("auto_legacy");
    // 관리자가 바꾼 회원 (변경권 미사용, 잠기지 않음) — DB confirm_dibay_id 와 같이 변경 가능 (D13)
    expect(resolvePublicIdCanChange({ dibay_id: "lynkim", dibay_id_auto_assigned: false, dibay_id_locked: false })).toBe(true);
    expect(resolvePublicIdCanChange({ dibay_id: "hoon88", dibay_id_changed_once: true, dibay_id_locked: true })).toBe(false);
    expect(resolvePublicIdCanChange({ dibay_id: "x1234", dibay_id_can_change: false, dibay_id_auto_assigned: true })).toBe(false);
  });

  it("5 digits + 3 letters is a system-only auto id shape", () => {
    expect(isAutoGeneratedDibayId("48213sun")).toBe(true);
    expect(isAutoGeneratedDibayId("00000ace")).toBe(true);
    expect(isAutoGeneratedDibayId("4821sun")).toBe(false);
    expect(isValidDibayIdFormat("48213sun")).toBe(false);
    expect(isValidDibayIdFormat("48213suns")).toBe(true);
    expect(isDefaultDibayPublicId("48213sun")).toBe(true);
    expect(isDefaultDibayPublicId("dibay482913")).toBe(true);
  });
});
