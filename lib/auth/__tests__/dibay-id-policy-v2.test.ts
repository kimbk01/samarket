import { describe, expect, it } from "vitest";
import {
  dibayIdErrorMessageKo,
  dibayIdSimilarityKey,
  isAutoGeneratedDibayId,
  isSystemReservedDibayIdPrefix,
  isValidDibayIdFormat,
} from "@/lib/auth/dibay-id-policy";

describe("@id v2 (설계안 ⑦⑧)", () => {
  it("자동 발급 형식 — 신규 dibay+숫자 6~7자리, 기존 dibay_hex6 모두 인식", () => {
    expect(isAutoGeneratedDibayId("dibay482913")).toBe(true);
    expect(isAutoGeneratedDibayId("dibay0000001")).toBe(true);
    expect(isAutoGeneratedDibayId("dibay_9d830a")).toBe(true);
    expect(isAutoGeneratedDibayId("dibay12345")).toBe(false);
    expect(isAutoGeneratedDibayId("dibayapple")).toBe(false);
  });

  it("dibay 접두는 사용자·관리자 지정 불가", () => {
    for (const v of ["dibay123456", "dibay.123456", "dibay_abc", "dibayapple", "dibay.official"]) {
      expect(isSystemReservedDibayIdPrefix(v), v).toBe(true);
      expect(isValidDibayIdFormat(v), v).toBe(false);
    }
    expect(isValidDibayIdFormat("kim_bk")).toBe(true);
  });

  it("비슷한 아이디 키 — 점·밑줄·대소문자 무시", () => {
    expect(dibayIdSimilarityKey("Kim_BK")).toBe("kimbk");
    expect(dibayIdSimilarityKey("kim.bk")).toBe("kimbk");
    expect(dibayIdSimilarityKey("@kimbk")).toBe("kimbk");
  });

  it("오류 안내 문구", () => {
    expect(dibayIdErrorMessageKo("dibay_id_similar_taken")).toMatch(/비슷한 아이디/);
    expect(dibayIdErrorMessageKo("dibay_id_reserved_prefix")).toMatch(/dibay/);
    expect(dibayIdErrorMessageKo("unknown")).toBeNull();
  });
});
