import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { DIBAY_AUTO_ID_V3_RE, isAutoGeneratedDibayId } from "@/lib/auth/dibay-id-policy";
import { resolvePublicIdCanChange, resolvePublicIdState } from "@/lib/auth/dibay-public-id-ssot";
import { resolveMemberPublicIdUi } from "@/lib/auth/member-public-id-ui-contract";
import { publicFriendQrErrorCode } from "@/lib/community-messenger/friend-qr/friend-qr-contract";
import { normalizeCmFriendRequestSource } from "@/lib/community-messenger/friendship/cm-mutual-friend-request";

const read = (p: string) => readFileSync(join(process.cwd(), p), "utf8");
const fixSql = read("supabase/migrations/20271111170000_member_id_v3_audit_fixes.sql");
const v3Sql = read("supabase/migrations/20271111160000_member_id_v3_state_search_qr.sql");

function fn(sql: string, name: string): string {
  const start = sql.indexOf(`CREATE OR REPLACE FUNCTION public.${name}(`);
  expect(start, name).toBeGreaterThanOrEqual(0);
  return sql.slice(start, sql.indexOf("$function$;", start));
}

/** 회원 아이디 v3 재감사 수정 (2026-11-11) — 설계안 §9 */
describe("member id v3 audit fixes", () => {
  it("D1: one SQL helper for system auto ids, same shapes as TS; v3 shape = generated column", () => {
    const helper = fn(fixSql, "dibay_is_system_auto_id");
    expect(helper).toContain("'^([0-9]{5}[a-z]{3}|dibay[0-9]{6,7}|dibay_[a-f0-9]{6})$'");
    for (const name of ["assign_auto_dibay_id", "confirm_dibay_id", "admin_set_dibay_id"]) {
      const body = fn(fixSql, name);
      expect(body).toContain("public.dibay_is_system_auto_id(");
      expect(body).not.toMatch(/dibay_\[a-f0-9\]\{6\}\|dibay\[0-9\]/);
    }
    for (const v of ["48213sun", "00000ace", "dibay482913", "dibay0000001", "dibay_9d830a"]) expect(isAutoGeneratedDibayId(v)).toBe(true);
    for (const v of ["4821sun", "dibay12345", "kim.bk", "48213suns"]) expect(isAutoGeneratedDibayId(v)).toBe(false);
    expect(v3Sql).toContain(`lower(btrim(dibay_id)) ~ '${DIBAY_AUTO_ID_V3_RE.source}' THEN 'auto'`);
  });

  it("D2: TS state/can-change fallback = DB generated column cases (prod groups 2026-11-11)", () => {
    const legacy = { dibay_id: "dibay_0d9d04", dibay_id_initial: "dibay_0d9d04", dibay_id_auto_assigned: true, dibay_id_changed_once: false, dibay_id_locked: false };
    expect([resolvePublicIdState(legacy), resolvePublicIdCanChange(legacy)]).toEqual(["auto_legacy", true]);
    const fresh = { ...legacy, dibay_id: "48213sun", dibay_id_initial: "48213sun" };
    expect([resolvePublicIdState(fresh), resolvePublicIdCanChange(fresh)]).toEqual(["auto", true]);
    const changed = { dibay_id: "hoon88", dibay_id_initial: "dibay_778d44", dibay_id_auto_assigned: false, dibay_id_changed_once: true, dibay_id_locked: true };
    expect([resolvePublicIdState(changed), resolvePublicIdCanChange(changed)]).toEqual(["custom", false]);
    const adminChanged = { dibay_id: "lynkim", dibay_id_initial: "dibay_0d9d04", dibay_id_auto_assigned: false, dibay_id_changed_once: false, dibay_id_locked: false };
    expect([resolvePublicIdState(adminChanged), resolvePublicIdCanChange(adminChanged)]).toEqual(["custom", true]);
    const lockedCustom = { dibay_id: "jjchoi", dibay_id_initial: "jjchoi", dibay_id_auto_assigned: false, dibay_id_changed_once: false, dibay_id_locked: true };
    expect([resolvePublicIdState(lockedCustom), resolvePublicIdCanChange(lockedCustom)]).toEqual(["custom", false]);
    expect(v3Sql).toContain("AND NOT COALESCE(dibay_id_changed_once, false)\n    AND (COALESCE(dibay_id_auto_assigned, false) OR NOT COALESCE(dibay_id_locked, false))");
  });

  it("E7: confirm_dibay_id uses the generated change column; N6: logs member change before→after", () => {
    const body = fn(fixSql, "confirm_dibay_id");
    expect(body).toContain("IF v_before IS NOT NULL AND NOT COALESCE(v_row.dibay_id_can_change, false) THEN");
    expect(body).toContain("'member_dibay_id_change'");
    expect(body).toContain("jsonb_build_object('before', v_before, 'after', v_normalized");
    expect(read("app/api/admin/users/[id]/member-id/route.ts")).toContain('"member_dibay_id_change",');
  });

  it("E2: grant only for members who used their change (DB + admin button)", () => {
    expect(fn(fixSql, "admin_grant_dibay_id_change")).toContain("'change_right_not_used'");
    expect(read("components/admin/users/AdminMemberIdPanel.tsx")).toContain("!data.canChange && data.changedOnce && data.current");
  });

  it("E3·N1: friend request records source on insert and reopen; callers pass their source", () => {
    const body = fn(fixSql, "cm_send_friend_request");
    expect(fixSql).toContain("DROP FUNCTION IF EXISTS public.cm_send_friend_request(uuid, uuid, text);");
    expect(body).toContain("source = v_source");
    expect(body).toContain("VALUES (p_requester_id, p_addressee_id, 'pending', coalesce(p_note, ''), v_source)");
    expect(fixSql).toContain("GRANT EXECUTE ON FUNCTION public.cm_send_friend_request(uuid, uuid, text, text) TO service_role;");
    expect(normalizeCmFriendRequestSource("contacts")).toBe("contacts");
    expect(normalizeCmFriendRequestSource("qr")).toBeUndefined();
    expect(read("components/community-messenger/contacts/use-contacts-friend-cta.ts")).toContain('undefined, "contacts")');
    expect(read("components/community-messenger/CommunityMessengerHome.tsx")).toContain(
      'source: "id_search" | "contacts" | "profile" = "id_search"',
    );
  });

  it("E1: availability check = DB dibay_id_candidate_error (same as confirm)", () => {
    const src = read("lib/auth/dibay-id-api-handlers.ts");
    expect(src).toContain('sb.rpc("dibay_id_candidate_error"');
    expect(src).not.toContain('.ilike("dibay_id"');
  });

  it("E4: hint says search is off when the member turned ID search off", () => {
    const row = { dibay_id: "48213sun", dibay_id_state: "auto", dibay_id_can_change: true };
    expect(resolveMemberPublicIdUi(row).hintKey).toBe("member_id_hint_auto");
    expect(resolveMemberPublicIdUi(row, { allowIdSearch: false })).toMatchObject({
      hintKey: "member_id_hint_search_off",
      hintVars: { digits: "" },
    });
  });

  it("L1: QR API error codes never reveal block / QR-off", () => {
    expect(publicFriendQrErrorCode("blocked_target")).toBe("qr_unusable");
    expect(publicFriendQrErrorCode("qr_disabled")).toBe("qr_unusable");
    expect(publicFriendQrErrorCode("qr_invalid")).toBe("qr_unusable");
    expect(publicFriendQrErrorCode("qr_self")).toBe("qr_self");
    for (const r of ["resolve", "add"]) {
      expect(read(`app/api/community-messenger/friend-qr/${r}/route.ts`)).toContain("publicFriendQrErrorCode(res.error)");
    }
  });

  it("L2·L3·E5: no id as name on /f, camera stream fully released, launch URL marked after handling", () => {
    expect(read("lib/community-messenger/friend-qr/friend-qr.server.ts")).not.toContain("|| dibayId ||");
    const cam = read("lib/qr/use-qr-camera-scanner.ts");
    expect(cam).toContain("videoRef.current.srcObject = null");
    const listener = read("components/community-messenger/friend-qr/FriendQrAppLinkListener.tsx");
    expect(listener).toMatch(/if \(!cancelled && !launchUrlConsumed\) \{\s+launchUrlConsumed = true;\s+handle\(launch\?\.url\);/);
  });

  it("N2·N3·N4·N5: QR badge, share/copy, regenerate row, public profile API by member id", () => {
    expect(read("app/api/community-messenger/users/resolve/route.ts")).toContain("friend_source: friendSource,");
    expect(read("components/community-messenger/MessengerFriendProfileSheet.tsx")).toContain('resolvedForThis?.friendSource === "qr"');
    const me = read("components/mypage/profile/MypageSelfProfileView.tsx");
    expect(me).toContain('data-testid="mypage-share-profile"');
    expect(me).toContain('data-testid="mypage-copy-id"');
    expect(read("components/my/settings/MemberDiscoverySettingsSection.tsx")).toContain('data-testid="member-qr-regenerate-row"');
    for (const f of [
      "app/api/users/by-username/[username]/public-profile/route.ts",
      "app/api/users/by-username/[username]/community-posts/route.ts",
      "app/(main)/u/[username]/page.tsx",
    ]) {
      expect(read(f)).toMatch(/findProfileByMemberId(<[^>]+>)?\(/);
    }
  });

  it("D3·D4: screens use the single contract; edit form does not write DB state itself", () => {
    expect(read("lib/mypage/mypage-home-required-items.ts")).toContain("resolveMemberPublicIdUi(profile)");
    expect(read("components/my/edit/ProfileDibayIdSection.tsx")).not.toContain("publicIdView.canChangeOnce");
    const form = read("components/my/edit/ProfileEditForm.tsx");
    expect(form).not.toContain('dibay_id_state: "custom"');
    expect(form).not.toContain("dibay_id_can_change: false");
  });
});

