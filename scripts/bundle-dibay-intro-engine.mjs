/**
 * Bundle Dibay Intro runtime-entry into a sealed-pack engine.js artifact,
 * freeze ENGINE_SOURCE_HASH, and stage Pretendard for serverless NFT tracing.
 * Kept outside the Next App Route graph so Turbopack never follows esbuild.
 *
 * Usage: node scripts/bundle-dibay-intro-engine.mjs
 */
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "package.json"));
const esbuild = require("esbuild");

const ENGINE_ID = "dibay-intro-engine";
const ENGINE_VERSION = 1;
const ENGINE_FILES = [
  "lib/dibay-intro/engine/identity.ts",
  "lib/dibay-intro/engine/timeline.ts",
  "lib/dibay-intro/engine/media-fit.ts",
  "lib/dibay-intro/engine/layer-dom.ts",
  "lib/dibay-intro/engine/scene-dom.ts",
  "lib/dibay-intro/engine/player.ts",
  "lib/dibay-intro/engine/cta-action.ts",
  "lib/dibay-intro/engine/runtime-entry.ts",
  "lib/dibay-intro/geometry.ts",
];

const outFile = join(root, "lib/dibay-intro/engine/runtime-bundle.iife.js");
const hashOut = join(root, "lib/dibay-intro/engine/engine-source-hash.generated.ts");
const fontOutDir = join(root, "lib/dibay-intro/engine/assets");
const fontOut = join(fontOutDir, "PretendardVariable.woff2");
const fontSrc = join(
  root,
  "node_modules/pretendard/dist/web/variable/woff2/PretendardVariable.woff2",
);
const entry = join(root, "lib/dibay-intro/engine/runtime-entry.ts");

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  platform: "browser",
  format: "iife",
  target: ["es2020"],
  absWorkingDir: root,
  alias: { "@": root },
});

const file = result.outputFiles?.[0];
if (!file) {
  console.error("engine_bundle_failed");
  process.exit(1);
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, file.contents);
console.log(`wrote ${outFile} (${file.contents.byteLength} bytes)`);

const hash = createHash("sha256");
hash.update(`${ENGINE_ID}@${ENGINE_VERSION}\n`);
for (const rel of ENGINE_FILES) {
  hash.update(rel);
  hash.update("\n");
  hash.update(readFileSync(join(root, rel)));
  hash.update("\n");
}
const digest = hash.digest("hex");
writeFileSync(
  hashOut,
  [
    "/** AUTO-GENERATED by scripts/bundle-dibay-intro-engine.mjs — do not edit. */",
    `export const ENGINE_SOURCE_HASH = ${JSON.stringify(digest)} as const;`,
    "",
  ].join("\n"),
);
console.log(`wrote ${hashOut} (${digest})`);

mkdirSync(fontOutDir, { recursive: true });
copyFileSync(fontSrc, fontOut);
console.log(`wrote ${fontOut}`);
