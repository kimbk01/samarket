#!/usr/bin/env node
/**
 * Generate System Start build input from Admin-persisted StartupConfig JSON.
 *
 * Usage:
 *   node scripts/generate-system-start-build-input.mjs [--config=path.json]
 *
 * Writes:
 *   native/system-start/build-input.json
 *   android/app/src/main/res/values/colors_system_start.xml
 *
 * Does NOT download remote logo/background into drawable bins automatically
 * (network optional). Does NOT claim installed OS splash pixels updated.
 */

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

function parseArgs(argv) {
  const out = { config: null };
  for (const a of argv) {
    if (a.startsWith("--config=")) out.config = a.slice("--config=".length);
  }
  return out;
}

function normalizeHex(value, fallback = "#FFFCFC") {
  if (typeof value !== "string") return fallback;
  const t = value.trim();
  if (/^#[0-9A-Fa-f]{6}$/.test(t) || /^#[0-9A-Fa-f]{8}$/.test(t)) return t.slice(0, 7);
  return fallback;
}

function buildInputFromRaw(raw) {
  const bg =
    raw && typeof raw === "object" && raw.background && typeof raw.background === "object"
      ? raw.background
      : {};
  const logo =
    raw && typeof raw === "object" && raw.logo && typeof raw.logo === "object"
      ? raw.logo
      : {};
  const color = normalizeHex(
    bg.color || (raw && raw.backgroundColor) || "#FFFCFC",
  );
  const bgType = bg.type === "image" ? "image" : "solid";
  const logoSource = logo.source === "uploaded" ? "uploaded" : "default";
  const logoUrl =
    logoSource === "uploaded" && typeof logo.url === "string" ? logo.url : null;
  const updatedAt =
    typeof raw?.updatedAt === "string" ? raw.updatedAt : new Date().toISOString();

  return {
    schemaVersion: 1,
    kind: "SYSTEM_START",
    updatedAt,
    background: {
      type: bgType,
      color,
      imageUrl: bgType === "image" && typeof bg.imageUrl === "string" ? bg.imageUrl : null,
    },
    logo: {
      source: logoSource,
      url: logoUrl,
      widthPreset: typeof logo.widthPreset === "string" ? logo.widthPreset : "medium",
      customWidthPx:
        typeof logo.customWidthPx === "number" ? logo.customWidthPx : null,
    },
    apply: {
      mode: "APP_UPDATE_REQUIRED",
      publish: false,
      serviceApply: false,
    },
    targets: {
      android: {
        splashColorResource:
          "android/app/src/main/res/values/colors_system_start.xml",
        splashDrawableHint: "android/app/src/main/res/drawable/splash.png",
        logoDrawableHint:
          "android/app/src/main/res/drawable-hdpi/ic_dibay_splash_logo.png",
      },
      ios: {
        launchScreenStoryboard:
          "ios/App/App/Base.lproj/LaunchScreen.storyboard",
        logoImagesetHint:
          "ios/App/App/Assets.xcassets/DibayStartupLogo.imageset",
        splashImagesetHint: "ios/App/App/Assets.xcassets/Splash.imageset",
      },
    },
    status: {
      adminPersisted: true,
      buildInputGenerated: true,
      binaryRebuildRequired: true,
      installedPixelsProven: false,
      note:
        "Color XML generated. Logo/bg binary replacement requires media copy during release build. Store/Play upload is out of repo scope.",
    },
  };
}

function colorXml(hex) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/generate-system-start-build-input.mjs — do not hand-edit. -->
<resources>
    <color name="dibay_system_start_background">${hex}</color>
</resources>
`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  let raw = {};
  if (args.config) {
    const p = resolve(root, args.config);
    if (!existsSync(p)) {
      console.error(`config not found: ${p}`);
      process.exit(1);
    }
    raw = JSON.parse(readFileSync(p, "utf8"));
    if (raw && typeof raw === "object" && raw.config) raw = raw.config;
  } else {
    const fallback = resolve(root, "native/system-start/admin-config.snapshot.json");
    if (existsSync(fallback)) {
      raw = JSON.parse(readFileSync(fallback, "utf8"));
      if (raw && typeof raw === "object" && raw.config) raw = raw.config;
    }
  }

  const input = buildInputFromRaw(raw);
  const outDir = resolve(root, "native/system-start");
  mkdirSync(outDir, { recursive: true });
  const outJson = resolve(outDir, "build-input.json");
  writeFileSync(outJson, `${JSON.stringify(input, null, 2)}\n`, "utf8");

  const colorPath = resolve(
    root,
    "android/app/src/main/res/values/colors_system_start.xml",
  );
  mkdirSync(dirname(colorPath), { recursive: true });
  writeFileSync(colorPath, colorXml(input.background.color), "utf8");

  console.log(
    JSON.stringify(
      {
        ok: true,
        buildInput: "native/system-start/build-input.json",
        androidColor: "android/app/src/main/res/values/colors_system_start.xml",
        backgroundColor: input.background.color,
        logoSource: input.logo.source,
        binaryRebuildRequired: true,
        installedPixelsProven: false,
      },
      null,
      2,
    ),
  );
}

main();
