#!/usr/bin/env node
/**
 * FIN-10 · 저장소 기대 스키마 매니페스트 생성 (DB 접속 없음).
 * supabase/migrations/*.sql 을 파일명 순으로 재생해 required-objects.json 을 결정적으로(정렬) 쓴다.
 *
 * Usage:
 *   node scripts/prod-schema-drift/build-manifest.mjs           # required-objects.json 갱신
 *   node scripts/prod-schema-drift/build-manifest.mjs --check   # 파일이 최신이 아니면 exit 1
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildManifest } from "./lib.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const MIGRATIONS_DIR = join(ROOT, "supabase", "migrations");
export const MANIFEST_PATH = join(HERE, "required-objects.json");

export function readMigrations(dir = MIGRATIONS_DIR) {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((name) => ({ name, sql: readFileSync(join(dir, name), "utf8") }));
}

/** @param {{ name: string, sql: string }[]} files */
export function renderManifest(files) {
  const sorted = [...files].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const m = buildManifest(sorted);
  const doc = {
    _comment:
      "GENERATED by scripts/prod-schema-drift/build-manifest.mjs from supabase/migrations — do not edit by hand.",
    migrationCount: sorted.length,
    lastMigration: sorted.length ? sorted[sorted.length - 1].name : null,
    tables: m.tables,
    functions: m.functions,
  };
  return JSON.stringify(doc, null, 2) + "\n";
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderManifest(readMigrations());
  if (process.argv.includes("--check")) {
    const cur = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, "utf8") : "";
    if (cur !== text) {
      console.error("[prod-schema-drift] required-objects.json is stale — run build-manifest.mjs");
      process.exit(1);
    }
    console.log("[prod-schema-drift] required-objects.json up to date");
  } else {
    writeFileSync(MANIFEST_PATH, text);
    const doc = JSON.parse(text);
    const cols = Object.values(doc.tables).reduce((s, c) => s + c.length, 0);
    console.log(
      `[prod-schema-drift] wrote ${MANIFEST_PATH}: ${Object.keys(doc.tables).length} tables, ${cols} columns, ${doc.functions.length} functions`,
    );
  }
}
