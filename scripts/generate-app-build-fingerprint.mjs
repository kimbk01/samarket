#!/usr/bin/env node
/**
 * Writes auth/QA build provenance (no secrets).
 * - lib/build/generated-app-build-fingerprint.ts
 * - ios Info.plist Dibay* keys (native install proof)
 * - optional android assets JSON
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function run(cmd) {
  try {
    return execSync(cmd, { cwd: ROOT, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
}

function detectBuildConfiguration() {
  const fromEnv = String(process.env.DIBAY_BUILD_CONFIGURATION ?? "").trim();
  if (fromEnv) return fromEnv;
  if (process.env.CI === "true" || process.env.VERCEL === "1") return "ci";
  return "debug";
}

function main() {
  const gitShaFull = run("git rev-parse HEAD") || "unknown";
  const gitSha = gitShaFull.slice(0, 12);
  const gitDirty = run("git status --porcelain") ? true : false;
  const buildTimestamp = new Date().toISOString();
  const buildConfiguration = detectBuildConfiguration();
  const bundleId = "com.dibay.app";
  const webDeploySha =
    String(process.env.VERCEL_GIT_COMMIT_SHA ?? process.env.NEXT_PUBLIC_VERCEL_GIT_COMMIT_SHA ?? "")
      .trim()
      .slice(0, 12) || null;

  const fingerprint = {
    gitSha,
    gitShaFull,
    gitDirty,
    buildTimestamp,
    buildConfiguration,
    bundleId,
    webDeploySha,
    environment: String(process.env.DIBAY_BUILD_ENVIRONMENT ?? process.env.NODE_ENV ?? "development"),
  };

  const tsOut = path.join(ROOT, "lib/build/generated-app-build-fingerprint.ts");
  fs.mkdirSync(path.dirname(tsOut), { recursive: true });
  fs.writeFileSync(
    tsOut,
    `/* AUTO-GENERATED by scripts/generate-app-build-fingerprint.mjs — do not edit by hand */\n` +
      `export const GENERATED_APP_BUILD_FINGERPRINT = ${JSON.stringify(fingerprint, null, 2)} as const;\n`,
    "utf8",
  );

  const iosInfo = path.join(ROOT, "ios/App/App/Info.plist");
  if (fs.existsSync(iosInfo)) {
    const pairs = [
      ["DibayGitSha", fingerprint.gitSha],
      ["DibayGitShaFull", fingerprint.gitShaFull],
      ["DibayBuildTimestamp", fingerprint.buildTimestamp],
      ["DibayBuildConfiguration", fingerprint.buildConfiguration],
      ["DibayGitDirty", fingerprint.gitDirty ? "true" : "false"],
    ];
    for (const [key, value] of pairs) {
      const safe = String(value).replace(/'/g, "'\\''");
      try {
        execSync(`plutil -replace ${key} -string '${safe}' "${iosInfo}"`, {
          cwd: ROOT,
          stdio: "pipe",
        });
      } catch {
        try {
          execSync(`plutil -insert ${key} -string '${safe}' "${iosInfo}"`, {
            cwd: ROOT,
            stdio: "pipe",
          });
        } catch (err) {
          console.warn(`[generate-app-build-fingerprint] Info.plist ${key} skipped:`, err?.message ?? err);
        }
      }
    }
  }

  const androidAssetDir = path.join(ROOT, "android/app/src/main/assets");
  if (fs.existsSync(androidAssetDir)) {
    fs.writeFileSync(
      path.join(androidAssetDir, "dibay-build-fingerprint.json"),
      `${JSON.stringify(fingerprint, null, 2)}\n`,
      "utf8",
    );
  }

  console.log(
    `[generate-app-build-fingerprint] gitSha=${fingerprint.gitSha} config=${fingerprint.buildConfiguration} dirty=${fingerprint.gitDirty}`,
  );
}

main();
